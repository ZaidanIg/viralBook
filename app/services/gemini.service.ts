import { GoogleGenAI, Schema } from "@google/genai";

let genAIInstance: GoogleGenAI | null = null;

export const getGeminiClient = (): GoogleGenAI => {
  let apiKey = '';
  if (typeof window !== 'undefined') {
    apiKey = localStorage.getItem('USER_GEMINI_API_KEY') || "";
  }
  if (!apiKey) {
    apiKey = process.env.API_KEY || process.env.GEMINI_API_KEY || "";
  }
  if (!apiKey) {
    throw new Error("Gemini API Key is missing. Please set it in your environment settings.");
  }
  
  // Create a new instance every time to ensure it picks up changes from localStorage
  return new GoogleGenAI({ apiKey });
};

// Architecture heavily optimized towards Free Tier constraints:
export const getModelConfigs = () => {
  if (typeof window !== 'undefined') {
    const customKey = localStorage.getItem('USER_GEMINI_API_KEY');
    let customModel = localStorage.getItem('CUSTOM_USER_MODEL');
    if (customModel === 'gemini-2.5-flash-lite' || customModel === 'gemini-2.0-flash-lite-preview-02-05' || customModel === 'gemini-2.5-flash' || customModel === 'gemini-flash-latest' || customModel === 'gemini-1.5-flash') {
       customModel = 'gemini-3.5-flash';
    }
    if (customKey && customModel) {
      return {
        strategist: customModel,
        outline: customModel,
        writer: customModel,
        review: customModel,
        image: "gemini-3.5-flash" // Free-tier fallbacks will handle images
      };
    }
  }
  
  return {
    strategist: "gemini-3.5-flash", 
    outline: "gemini-3.5-flash",
    writer: "gemini-3.5-flash", 
    review: "gemini-3.5-flash",
    image: "gemini-3.5-flash"
  };
};

