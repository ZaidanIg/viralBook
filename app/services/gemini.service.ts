export class GeminiService {
  /**
   * Unified interface for hitting Gemini endpoints with enforced structured JSON.
   */
  static async requestStructured<T>(
    modelType: keyof ReturnType<typeof getModelConfigs>,
    prompt: string, 
    schema: Schema, 
    retries = 2
  ): Promise<T> {
    const targetModel = getModelConfigs()[modelType];
    const ai = getGeminiClient();
    
    let lastError: any;
    for (let attempt = 1; attempt <= retries; attempt++) {
      try {
        const response = await ai.models.generateContent({
          model: targetModel,
          contents: prompt,
          config: {
            responseMimeType: "application/json",
            responseSchema: schema,
            temperature: 0.5, 
          }
        });

        if (response.text) {
          return JSON.parse(response.text) as T;
        }
        throw new Error("Empty response body from model.");
      } catch (error: any) {
        console.error(`[GeminiService] attempt ${attempt} failed on ${modelType}:`, error);
        lastError = error;
      }
    }
    throw lastError || new Error(`Max retries exceeded for model: ${modelType}`);
  }

  /**
   * Unstructured fast text request
   */
  static async requestText(modelType: keyof ReturnType<typeof getModelConfigs>, prompt: string, retries = 1): Promise<string> {
    const targetModel = getModelConfigs()[modelType];
    const ai = getGeminiClient();
    let lastError: any;
    for (let attempt = 1; attempt <= retries; attempt++) {
      try {
        const response = await ai.models.generateContent({
          model: targetModel,
          contents: prompt
        });

        if (response.text) {
          return response.text.trim();
        }
      } catch (error: any) {
        console.error(`[GeminiService] text attempt ${attempt} failed on ${modelType}:`, error);
        lastError = error;
      }
    }
    throw lastError || new Error("Max text retries exceeded");
  }

  static async requestImage(prompt: string, editImageUrl?: string): Promise<string> {
    try {
      const ai = getGeminiClient();
      const response = await ai.models.generateContent({
        model: 'gemini-2.5-flash-image',
        contents: {
          parts: [
            {
              text: prompt,
            },
          ],
        },
        config: {
          imageConfig: {
            aspectRatio: "9:16",
          },
        },
      });

      for (const part of response.candidates?.[0]?.content?.parts || []) {
        // Find the image part, do not assume it is the first part.
        if (part.inlineData) {
          const base64EncodeString: string = part.inlineData.data;
          return `data:image/jpeg;base64,${base64EncodeString}`;
        }
      }
      throw new Error("No image generated by Gemini API");
    } catch (e: any) {
      console.warn('Image generation failed, falling back to placeholder', e);
      // Fallback
      const seed = Math.floor(Math.random() * 1000000);
      const encodedPrompt = encodeURIComponent(prompt);
      return `https://image.pollinations.ai/prompt/${encodedPrompt}?width=800&height=1200&seed=${seed}&nologo=true`;
    }
  }
}
